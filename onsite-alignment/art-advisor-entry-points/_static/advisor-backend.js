/* Published static copy only: vac-art-advisor/serve.py, in the browser.
 *
 * Answers the advisor's own endpoints from window.aaRecordings (written by _publish.py from the
 * same fixtures serve.py replays), at serve.py's pacing. The turn counter lives in sessionStorage
 * so a minimised, closed or reloaded advisor carries on where the server would have.
 */
(function () {
  const REC = window.aaRecordings;
  const STREAM_DELAY = 50, SEARCH_PAUSE = 1800, EVENT_PAUSE = 400;   // ms, as serve.py
  const TURN_KEY = 'aa:static-turn';

  function parseSse(raw) {
    return raw.split('\n\n').filter(b => b.trim()).map(block => {
      let name = 'message', data = '';
      block.split('\n').forEach(line => {
        if (line.startsWith('event:')) name = line.slice(6).trim();
        else if (line.startsWith('data:')) data += line.slice(5).trim();
      });
      return [name, data];
    });
  }
  const TURNS = { de: REC.de.turns.map(t => parseSse(t.sse)), en: REC.en.turns.map(t => parseSse(t.sse)) };
  const CARDS = {};
  TURNS.en.forEach(turn => turn.forEach(([name, data]) => {
    if (name === 'artworks') JSON.parse(data).artworks.forEach(c => { CARDS[c.motif_id] = c; });
  }));

  const turn = {
    get: () => { try { return +sessionStorage.getItem(TURN_KEY) || 0; } catch (e) { return 0; } },
    set: n => { try { sessionStorage.setItem(TURN_KEY, String(n)); } catch (e) { /* private mode */ } },
  };
  const asDeltas = (text, size = 24) => {
    const out = [];
    for (let i = 0; i < text.length; i += size) out.push(['delta', JSON.stringify({ text: text.slice(i, i + size) })]);
    return out;
  };

  function replacementReply(message, kept) {
    const slot = message.includes('[[replace:') ? message.split('[[replace:')[1].split(']]')[0] : '';
    const candidates = Object.values(CARDS).filter(c => !kept.has(c.motif_id) && c.motif_id !== slot).slice(0, 3);
    const head = message.includes('Der Kunde') ? 'Hier sind drei Alternativen, die zu Ihrer Wand passen:' : 'Here are three alternatives that fit your wall:';
    const text = [head, ...candidates.map(c => `[[swap:${c.motif_id}]] ${c.title}, ${c.artist}`)].join('\n') + `\n[[replace:${slot}]]`;
    return [['status', JSON.stringify({ state: 'searching' })], ['artworks', JSON.stringify({ artworks: candidates })], ...asDeltas(text)];
  }
  function roomPhotoReply(message) {
    return asDeltas(message.startsWith('[Der Kunde')
      ? 'Wie breit und hoch ist die freie Wandfläche, an die das Werk kommen soll?\n[[options:200 × 150 cm|300 × 220 cm|Weiß ich noch nicht]]'
      : 'How wide and how high is the free wall area for the work?\n[[options:200 × 150 cm|300 × 220 cm|Not sure yet]]');
  }
  function nextEvents(body) {
    const message = body.message || '';
    if (message.startsWith('[') && message.includes('[[swap:')) return replacementReply(message, new Set(body.kept || []));
    if (message.startsWith('[') && (message.includes('Foto seines Raums') || message.includes('photo of their room'))) return roomPhotoReply(message);
    const turns = TURNS[body.lang] || TURNS.en;
    const n = turn.get();
    turn.set(n + 1);
    return turns[Math.min(n, turns.length - 1)];
  }

  function stream(events) {
    const enc = new TextEncoder();
    const wait = ms => new Promise(r => setTimeout(r, ms));
    return new ReadableStream({
      async start(controller) {
        for (const [name, data] of events) {
          controller.enqueue(enc.encode(`event: ${name}\ndata: ${data}\n\n`));
          await wait(name === 'delta' ? STREAM_DELAY : name === 'status' ? SEARCH_PAUSE : EVENT_PAUSE);
        }
        if (!events.length || events[events.length - 1][0] !== 'done') controller.enqueue(enc.encode('event: done\ndata: {}\n\n'));
        controller.close();
      },
    });
  }
  const json = payload => new Response(JSON.stringify(payload), { headers: { 'Content-Type': 'application/json' } });
  const readBody = init => { try { return JSON.parse(init?.body || '{}'); } catch (e) { return {}; } };

  function collectionPage(ids) {
    const esc = s => String(s || '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
    const items = ids.map(id => CARDS[id] || { title: id }).map(c =>
      `<li><img src="${esc(c.image_url)}" alt=""><b>${esc(c.title)}</b> ${esc(c.artist)}</li>`).join('');
    const html = '<!doctype html><meta charset=utf-8><meta name="robots" content="noindex,nofollow"><title>Selection (stand-in)</title>'
      + '<style>body{font:15px system-ui;margin:40px}li{list-style:none;margin:0 0 24px}img{display:block;max-width:320px;height:auto}</style>'
      + `<p>Stand-in. The real collection page is generated by the Art Advisor service.</p><ul>${items}</ul>`;
    return URL.createObjectURL(new Blob([html], { type: 'text/html' }));
  }

  const ENDPOINTS = {
    '/chat/stream': init => new Response(stream(nextEvents(readBody(init))), { headers: { 'Content-Type': 'text/event-stream' } }),
    '/motif/sizes': init => {
      const id = String(readBody(init).motif_id || '');
      const card = CARDS[id] || {};
      return json(REC.en.sizes[id] || { sizes: [{ sku: card.sku, width_mm: card.width_mm, height_mm: card.height_mm, price_from_cents: card.price_from_cents, product_url: card.product_url }] });
    },
    '/room-photo': () => new Promise(r => setTimeout(() => r(json({ ok: true,
      description: 'Heller Wohnraum, Nordlicht, warme Holztöne, beigefarbenes Sofa, skandinavisch-minimalistisch, ruhige Stimmung. (Attrappe)' })), 1200)),
    '/collection': init => json({ url: collectionPage(readBody(init).motif_ids || []) }),
    '/click': () => json({ ok: true }),
    '/reset': () => { turn.set(0); return json({ ok: true }); },
  };

  const realFetch = window.fetch.bind(window);
  window.fetch = (input, init) => {
    const url = typeof input === 'string' ? input : input?.url || '';
    const handler = ENDPOINTS[url.split('?')[0]];
    return handler ? Promise.resolve(handler(init)) : realFetch(input, init);
  };
  // product links: captured pages of this copy, else live lumas.de
  window.aaShopLink = path => window.aaStatic.shopLink(path);
})();
